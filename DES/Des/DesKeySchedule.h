// ============================================================================
//  DesKeySchedule.h
//  Генерація 16-ти 48-бітних ключів раундів K(1)..K(16) з 64-бітного ключа
//  (рис. 3.5 методички). Виконується ОДИН раз для ключа, а не для кожного
//  блоку (п. 1 базової оптимізації).
// ============================================================================
#pragma once

#include "../Common/Platform.h"

// ----------------------------------------------------------------------------
//  Ключ раунду в оптимізованому вигляді.
//
//  У функції F (див. DesCore.h) 32-бітна права половина R розширюється до
//  34-бітного числа W = [R32 | R1 R2 ... R32 | R1] (лише 2 зсуви та 2 OR).
//  6-бітна група для S-box №i (i = 1..8) — це біти W на зсуві 32 - 4i.
//  Сусідні групи перекриваються на 2 біти (так працює функція E), але
//  НЕПАРНІ групи (1,3,5,7) між собою не перекриваються, так само як і
//  ПАРНІ (2,4,6,8). Тому 48-бітний ключ раунду заздалегідь розкладається
//  на два 64-бітні числа, де кожна 6-бітна частина ключа вже стоїть
//  навпроти "своєї" групи W:
//      oddGroups  — частини ключа для S1, S3, S5, S7;
//      evenGroups — частини ключа для S2, S4, S6, S8.
//  У результаті операція "E(R) XOR K(i)" виконується всього двома XOR.
// ----------------------------------------------------------------------------
struct DesRoundKey
{
    uint64_t oddGroups;
    uint64_t evenGroups;
};

class DesKeySchedule
{
public:
    static constexpr unsigned ROUNDS = 16;

    // Стандартні 48-бітні ключі раундів (біт №1 — старший з 48).
    // rawKeys[0] = K(1), ..., rawKeys[15] = K(16).
    static void GenerateRaw(uint64_t key, uint64_t rawKeys[ROUNDS]);

    // Ключі раундів в оптимізованому вигляді для DesCore.
    // encryptKeys — у порядку K(1)..K(16) (для шифрування),
    // decryptKeys — у зворотному порядку K(16)..K(1) (для дешифрування).
    static void Generate(uint64_t key, DesRoundKey encryptKeys[ROUNDS],
                         DesRoundKey decryptKeys[ROUNDS]);

    // Перетворення 48-бітного стандартного ключа раунду в оптимізований вигляд
    static DesRoundKey ToOptimized(uint64_t rawKey48);
};
