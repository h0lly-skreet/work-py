// ============================================================================
//  DesKeySchedule.h
//  Генерація 16-ти 48-бітних ключів раундів K(1)..K(16) з 64-бітного ключа
//  (рис. 3.5 методички). Виконується ОДИН раз для ключа, а не для кожного
//  блоку (п. 1 базової оптимізації).
// ============================================================================
#pragma once

#include "../Common/Platform.h"

// ----------------------------------------------------------------------------
//  Ключ раунду в оптимізованому вигляді.
//
//  Усередині раундів половини блоку L і R зберігаються ЦИКЛІЧНО ЗСУНУТИМИ
//  праворуч на 1 біт:  U = ROTR(R, 1)  (див. DesCore.h). У такому вигляді
//  функція розширення E виконується без жодної таблиці:
//    * у числі U 6-бітні групи для S1, S3, S5, S7 стоять на зсувах 26, 18, 10, 2;
//    * у числі V = ROTR(U, 4) групи для S2, S4, S6, S8 стоять на зсувах 18, 10, 2, 26.
//  (Сусідні групи E перекриваються на 2 біти, тому всі 8 груп одночасно в
//  одному 32-бітному числі не вміщуються — звідси два числа U і V.)
//
//  Тому 48-бітний ключ раунду заздалегідь розкладається на два 32-бітні
//  числа, де кожна 6-бітна частина ключа стоїть навпроти "своєї" групи:
//      uGroups — частини ключа для S1, S3, S5, S7 (накладаються на U);
//      vGroups — частини ключа для S2, S4, S6, S8 (накладаються на V).
//  У результаті "E(R) XOR K(i)" — це одна операція ROR і два XOR.
// ----------------------------------------------------------------------------
struct DesRoundKey
{
    uint32_t uGroups;
    uint32_t vGroups;
};

class DesKeySchedule
{
public:
    static constexpr unsigned ROUNDS = 16;

    // Стандартні 48-бітні ключі раундів (біт №1 — старший з 48).
    // rawKeys[0] = K(1), ..., rawKeys[15] = K(16).
    static void GenerateRaw(uint64_t key, uint64_t rawKeys[ROUNDS]);

    // Ключі раундів в оптимізованому вигляді для DesCore.
    // encryptKeys — у порядку K(1)..K(16) (для шифрування),
    // decryptKeys — у зворотному порядку K(16)..K(1) (для дешифрування).
    static void Generate(uint64_t key, DesRoundKey encryptKeys[ROUNDS],
                         DesRoundKey decryptKeys[ROUNDS]);

    // Перетворення 48-бітного стандартного ключа раунду в оптимізований вигляд
    static DesRoundKey ToOptimized(uint64_t rawKey48);
};
