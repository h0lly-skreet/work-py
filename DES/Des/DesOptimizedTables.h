//  DesOptimizedTables.h
//  ОПТИМІЗОВАНІ таблиці DES — "глибока оптимізація"
//
//  Готові змінені таблиці НЕ використовуються. Усі три набори таблиць
//  РОЗРАХОВУЮТЬСЯ при запуску програми зі стандартних таблиць
//  (DesStandardTables.h) методом Build() — код розрахунку в
//  DesOptimizedTables.cpp. Розрахунок займає частки мілісекунди.
//
//  Половини блоку L, R усередині раундів зберігаються циклічно зсунутими
//  праворуч на 1 біт (ROTR 1) — так розширення E робиться без таблиці
//  (DesKeySchedule.h, DesCore.h). Цей зсув також "вшито" в таблиці
//
//  1) SP[8][64] (uint32) — об'єднані S-box + перестановка P.
//     SP[i][x] = ROTR( P( S_{i+1}(x), розміщений на своїх 4-х позиціях ), 1 ).
//     Замість "S-box -> склеїти 8 результатів -> перестановка P по 32 бітах"
//     маємо 8 звертань до таблиць і 7 операцій OR.
//
//  2) IP[8][256] (uint64) — початкова перестановка через 8 таблиць по 256:
//     IP(x) = IP[0][байт0] | IP[1][байт1] | ... | IP[7][байт7].
//     Перестановка бітів лінійна, тому результат для всього числа = OR
//     результатів для кожного байта окремо. На виході — одразу
//     ROTR(L0, 1) у старших 32 бітах і ROTR(R0, 1) у молодших.
//
//  3) FP[8][256] (uint64) — кінцева перестановка IP^-1, аналогічно
//     (на вході — половини, зсунуті ROTR 1; зворотний зсув враховано в таблиці).
//
//  Порядок байтів. Блок читається з файлу ЄДИНИМ 64-бітним числом. На x64
//  (little-endian) 1-й байт файлу потрапляє в МОЛОДШИЙ байт числа, а за
//  стандартом DES 1-й байт — це біти 1..8 (старші). Ця різниця врахована
//  безпосередньо при розрахунку таблиць IP та FP: таблиця IP[j] індексується j-м байтом ФАЙЛУ,
//  а FP[j] одразу видає байти в порядку запису у файл. Окремих операцій
//  перестановки байтів (bswap) під час шифрування не потрібно.

#pragma once

#include "../Common/Platform.h"

class DesOptimizedTables
{
public:
    // Розраховує всі таблиці. Викликається автоматично один раз
    // при запуску програми (DesOptimizedTables.cpp).
    static bool Build();

    static uint32_t SP[8][64];
    static uint64_t IP[8][256];
    static uint64_t FP[8][256];

private:
    static void BuildSP();
    static void BuildIP();
    static void BuildFP();

    static const bool s_isBuilt;
};
