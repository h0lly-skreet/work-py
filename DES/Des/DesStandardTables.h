    //  Універсальна таблична перестановка з нумерацією бітів за стандартом.
    //
    //  input    — вхідне значення з inputBits бітів (біт №1 — старший);
    //  table    — таблиця перестановки: table[j] = номер вхідного біта, який
    //             стає (j+1)-м бітом результату;
    //  outBits  — довжина результату = кількість елементів таблиці.
    //
    //  Біт з номером n (нумерація з 1 зліва) знаходиться у числі на позиції
    //  (inputBits - n) у звичній для процесора нумерації (з 0 справа) —
    //  саме так враховується різниця нумерацій, про яку говорить методичка.
    // ------------------------------------------------------------------------
    static constexpr uint64_t Permute(uint64_t input, unsigned inputBits,
                                      const uint8_t* table, unsigned outBits)
    {
        uint64_t result = 0;
        for (unsigned j = 0; j < outBits; ++j)
        {
            const uint64_t bit = (input >> (inputBits - table[j])) & 1u;
            result |= bit << (outBits - 1 - j);
        }
        return result;
    }

    // Застосування S-box за правилом стандарту: 1-й і 6-й біти 6-бітної групи
    // дають номер рядка, біти 2..5 — номер стовпця.
    static constexpr uint8_t SBox(unsigned boxIndex, unsigned sixBits)
    {
        const unsigned row    = ((sixBits >> 4) & 0x2) | (sixBits & 0x1);
        const unsigned column = (sixBits >> 1) & 0xF;
        return S[boxIndex][row][column];
    }
